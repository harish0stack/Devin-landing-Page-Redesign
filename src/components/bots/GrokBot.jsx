  const r = w / 2;
  const s = Math.max(0, h / 2 - r);
  return `M ${-r} ${-s} A ${r} ${r} 0 0 1 ${r} ${-s} L ${r} ${s} A ${r} ${r} 0 0 1 ${-r} ${s} Z`;
